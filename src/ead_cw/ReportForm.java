    private void btnGenerateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerateActionPerformed
        String selectedReport =
                (String) cmbReportType.getSelectedItem();

        if (selectedReport == null
                || "-- Select Report --".equals(selectedReport)) {
            JOptionPane.showMessageDialog(this,
                    "Please select a report to generate.");
            return;
        }

        String reportFileName;

        switch (selectedReport) {
            case "Clinic Revenue and Service Report":
                reportFileName = "ClinicRevenueReport.jrxml";
                break;
            case "Appointment Schedule Report":
                reportFileName = "AppointmentScheduleReport.jrxml";
                break;
            case "Treatment History Report":
                reportFileName = "TreatmentHistoryReport.jrxml";
                break;
            case "Billable Item Usage Report":
                reportFileName = "BillableItemUsageReport.jrxml";
                break;
            default:
                JOptionPane.showMessageDialog(this,
                        "The selected report is not available.");
                return;
        }

        generateReport(reportFileName);
    }//GEN-LAST:event_btnGenerateActionPerformed

