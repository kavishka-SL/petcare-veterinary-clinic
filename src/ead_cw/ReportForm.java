    private void generateReport(String reportFileName) {
        String resourcePath = "/ead_cw/reports/" + reportFileName;

        try (InputStream reportFile = getClass().getResourceAsStream(
                    resourcePath);
             Connection connection = DBConnection.getConnection()) {

            if (reportFile == null) {
                JOptionPane.showMessageDialog(this,
                        "The selected report file could not be found.");
                return;
            }

            JasperReport report =
                    JasperCompileManager.compileReport(reportFile);
            JasperPrint print = JasperFillManager.fillReport(
                    report, new HashMap<>(), connection);

            if (print.getPages().isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "There are no records to display in this report.");
                return;
            }

            JasperViewer.viewReport(print, false);
        } catch (Exception exception) {
            JOptionPane.showMessageDialog(this,
                    "Unable to generate report: "
                    + exception.getMessage());
        }
    }

