    private boolean validateCustomerInputs() {
        String fullName = txtFullName.getText().trim();
        String phone = txtPhone.getText().trim();
        String email = txtEmail.getText().trim();
        String address = txtAddress.getText().trim();

        if (fullName.length() < 2 || fullName.length() > 100
                || !fullName.matches("\\p{L}[\\p{L} .'-]*")) {
            JOptionPane.showMessageDialog(this,
                    "Enter a valid full name using letters only.");
            txtFullName.requestFocus();
            return false;
        }

        if (!phone.matches("0\\d{9}")) {
            JOptionPane.showMessageDialog(this,
                    "Phone number must start with 0 and contain 10 digits.");
            txtPhone.requestFocus();
            return false;
        }

        if (!email.isEmpty()
                && !email.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}$")) {
            JOptionPane.showMessageDialog(this,
                    "Enter a valid email address or leave it empty.");
            txtEmail.requestFocus();
            return false;
        }

        if (address.length() < 5 || address.length() > 200) {
            JOptionPane.showMessageDialog(this,
                    "Address must contain between 5 and 200 characters.");
            txtAddress.requestFocus();
            return false;
        }

        return true;
    }

