    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String fullName = txtFullName.getText().trim();
        String phone = txtPhone.getText().trim();
        String email = txtEmail.getText().trim();
        String address = txtAddress.getText().trim();

        if (!validateCustomerInputs()) {
            return;
        }

        String sql = "INSERT INTO customers "
                + "(full_name, phone, email, address) VALUES (?, ?, ?, ?)";

        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setString(1, fullName);
            statement.setString(2, phone);
            statement.setString(3, email);
            statement.setString(4, address);
            statement.executeUpdate();

            JOptionPane.showMessageDialog(this, "Customer added successfully.");
            clearFields();
            loadCustomers();
        } catch (SQLException exception) {
            JOptionPane.showMessageDialog(this,
                    "Unable to add customer: " + exception.getMessage());
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int selectedRow = tblCustomers.getSelectedRow();

        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this,
                    "Please select a customer to delete.");
            return;
        }

        int customerId = Integer.parseInt(
                tblCustomers.getValueAt(selectedRow, 0).toString());
        String customerName =
                tblCustomers.getValueAt(selectedRow, 1).toString();

        int answer = JOptionPane.showConfirmDialog(
                this,
                "Delete customer " + customerName + "?",
                "Confirm Delete",
                JOptionPane.YES_NO_OPTION);

        if (answer != JOptionPane.YES_OPTION) {
            return;
        }

        String sql = "DELETE FROM customers WHERE customer_id = ?";

        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setInt(1, customerId);
            statement.executeUpdate();

            JOptionPane.showMessageDialog(this, "Customer deleted successfully.");
            clearFields();
            loadCustomers();
        } catch (SQLException exception) {
            JOptionPane.showMessageDialog(this,
                    "Unable to delete customer: " + exception.getMessage());
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        int selectedRow = tblCustomers.getSelectedRow();

        if (selectedRow < 0) {
            JOptionPane.showMessageDialog(this,
                    "Please select a customer to update.");
            return;
        }

        String fullName = txtFullName.getText().trim();
        String phone = txtPhone.getText().trim();
        String email = txtEmail.getText().trim();
        String address = txtAddress.getText().trim();

        if (!validateCustomerInputs()) {
            return;
        }

        int customerId = Integer.parseInt(
                tblCustomers.getValueAt(selectedRow, 0).toString());

        String sql = "UPDATE customers SET full_name = ?, phone = ?, "
                + "email = ?, address = ? WHERE customer_id = ?";

        try (Connection connection = DBConnection.getConnection();
             PreparedStatement statement = connection.prepareStatement(sql)) {

            statement.setString(1, fullName);
            statement.setString(2, phone);
            statement.setString(3, email);
            statement.setString(4, address);
            statement.setInt(5, customerId);
            statement.executeUpdate();

            JOptionPane.showMessageDialog(this, "Customer updated successfully.");
            clearFields();
            loadCustomers();
        } catch (SQLException exception) {
            JOptionPane.showMessageDialog(this,
                    "Unable to update customer: " + exception.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

