        if (selectedRow >= 0) {
            txtFullName.setText(
                    tblCustomers.getValueAt(selectedRow, 1).toString());
            txtPhone.setText(
                    tblCustomers.getValueAt(selectedRow, 2).toString());

            Object email = tblCustomers.getValueAt(selectedRow, 3);
            txtEmail.setText(email == null ? "" : email.toString());

            txtAddress.setText(
                    tblCustomers.getValueAt(selectedRow, 4).toString());
        }
